#!/usr/bin/env python3
"""Generate portable C defaults from verified binary evidence."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
schema = json.loads((ROOT / 'analysis/recovered_config.json').read_text())
assert len(schema['fields']) == 57

def literal(x):
    return f'{float(x):.9g}' + ('.0f' if float(x).is_integer() and abs(float(x)) < 1e8 else 'f')

rows = ['/* Generated by tools/generate_fields.py; evidence: analysis/recovered_config.json. */',
        'const LVField lv_fields[LV_CONFIG_FIELD_COUNT] = {']
for f in schema['fields']:
    values = f['default'] if f['type'] == 'color' else [f['default']]
    values += [0] * (4 - len(values))
    rows.append('    {' + json.dumps(f['key']) + ', LV_' + f['type'].upper() + ', {' +
                ', '.join(literal(v) for v in values) + '}, ' +
                literal(f.get('min', 0)) + ', ' + literal(f.get('max', 0)) + ', ' +
                str(int('min' in f)) + ', ' + hex(f['offsets'][0]) + '},')
rows.append('};')
(ROOT / 'core/LVFields.inc').write_text('\n'.join(rows) + '\n')
(ROOT / 'ios/recovered_config.json').write_text(json.dumps(schema, ensure_ascii=False, indent=2) + '\n')
